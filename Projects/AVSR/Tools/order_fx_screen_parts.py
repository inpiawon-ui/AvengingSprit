def main(screens, only=None):
    keys = []
    for screen, name, (anchor, w, h, n, cols, loop, desc) in [(sc, nm, v) for sc in screens for nm, v in SCREENS[sc].items()]:
        if only and name not in only:
            continue
        rows = (n + cols - 1) // cols
        mock = 'mock_fxstory_%s_%s.png' % (screen, 'v2' if screen == 'clear' else 'v1')
        if anchor.startswith('컷'):
            anchor_line = '앵커: 시안 %s 의 %s(왼쪽부터 컷 1 · 2 · 3, 각 720 폭)에 그려진 이 효과 — 그 모양 · 색을 그대로' % (mock, anchor)
        else:
            anchor_line = '앵커(시안에서 이 효과만 잘라 둔 것): Projects/AVSR/_exchange/in/anchor_fx/%s/%s.png' % (screen, anchor)
        body = TEMPLATE.format(screen=screen, anchor_line=anchor_line, name=name, desc=desc, w=w, h=h, n=n, cols=cols,
                               sw=w * cols, sh=h * rows, mock=mock)
        with open(os.path.join(EX, 'order_fxs_%s_%s.ps1' % (screen, name)), 'w', encoding='utf-8-sig') as f:
            f.write(body)
        keys.append('%s_%s' % (screen, name))
    with open(os.path.join(EX, 'run_fxs.ps1'), 'w', encoding='utf-8-sig') as f:
        f.write(RUN.replace('KEYS', ','.join("'%s'" % k for k in keys)))
    print(len(keys), 'orders')


